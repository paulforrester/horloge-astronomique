"""Generate firmware/spec_gen/spec_gen.h from spec/clock.yaml (architecture P5; firmware-design §5.1).

The header carries the controller constants, the stepper sockets, the sensors and the event
timings, plus a hash of clock.yaml that the firmware reports over MQTT and the simulator checks.

    python -m firmware.spec_gen.gen_spec            # rewrite the header
    python -m firmware.spec_gen.gen_spec --check    # exit 1 if it is out of date
"""

import argparse
import hashlib
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
SPEC = REPO / "spec" / "clock.yaml"
HEADER = Path(__file__).with_name("spec_gen.h")
DEFAULT_TIMEOUT_MS = 60000  # for events whose module is not designed yet


def ident(s: str) -> str:
    return "k" + "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p)


def render(spec_text: str) -> str:
    spec = yaml.safe_load(spec_text)
    ctl, sensors, events = spec["controller"], spec["sensors"], spec["events"]
    digest = hashlib.sha256(spec_text.encode("utf-8")).hexdigest()[:16]
    out = [
        "// GENERATED by firmware/spec_gen/gen_spec.py from spec/clock.yaml. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        '#include "../core/time_law.h"',
        "",
        "namespace horloge::spec {",
        "",
        f'constexpr const char* kSpecHash = "{digest}";  // sha256 of clock.yaml, first 16 hex',
        f"constexpr int64_t kUstepsPerMotorRev = {int(ctl['usteps_per_motor_rev'])};",
        f"constexpr int64_t kMeanTimeOffsetS = {int(ctl['mean_time_offset_s'])};",
        f"constexpr int32_t kCatchUpUstepsPerS = {int(ctl['catch_up_usteps_per_s'])};",
        "static_assert(kUstepsPerMotorRev == horloge::kUstepsPerMotorRev, \"clock.yaml and time_law.h disagree\");",
        "static_assert(kMeanTimeOffsetS == horloge::kMeanTimeOffsetS, \"clock.yaml and time_law.h disagree\");",
        "",
        "struct Axis { const char* id; TimeKind time; uint8_t bus; uint8_t addr; uint32_t reduction; };",
        f"constexpr int kAxisCount = {len(ctl['axes'])};",
        "constexpr Axis kAxes[kAxisCount] = {",
    ]
    reductions = spec["motor"]["reduction"]
    for a in ctl["axes"]:
        kind = "TimeKind::Mean" if a["time"] == "mean" else "TimeKind::Legal"
        red = int(reductions.get(a["id"], 1))
        out.append(f'    {{"{a["id"]}", {kind}, {int(a["bus"])}, {int(a["addr"])}, {red}}},')
    out += ["};", "", "enum Sensor : uint8_t {"]
    for i, s in enumerate(sensors):
        out.append(f"  {ident(s['id'])} = {i},  // {s['module']}, {s['kind']}, {s['part']}")
    out += [f"  kSensorCount = {len(sensors)}", "};", ""]
    out.append("// Release windows' half-widths in seconds [E] (docs/m1-design.md §9.4).")
    for s in sensors:
        if "window_half_min" in s:
            out.append(f"constexpr int32_t {ident(s['id'])}WindowS = {round(float(s['window_half_min']) * 60)};")
    out += ["", "// Event timings: nominal and timeout (2 x nominal [E]) in ms; 0 nominal = not designed yet."]
    for e in events:
        nom = e.get("nominal_s")
        nom_ms = 0 if nom is None else round(float(nom) * 1000)
        to_ms = DEFAULT_TIMEOUT_MS if nom is None else 2 * nom_ms
        per = f" per {e['per']}" if "per" in e else ""
        out.append(f"constexpr uint32_t {ident(e['id'])}NominalMs = {nom_ms};{'  //' + per if per else ''}")
        out.append(f"constexpr uint32_t {ident(e['id'])}TimeoutMs = {to_ms};{'  //' + per if per else ''}")
    out += ["", "}  // namespace horloge::spec", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(SPEC.read_text(encoding="utf-8"))
    if args.check:
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != text:
            print("spec_gen.h is out of date: run python -m firmware.spec_gen.gen_spec")
            return 1
        return 0
    HEADER.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
